/**
 * Dynamically register a new language pack at runtime.
 * Enables adding ANY language (e.g. Arabic, French, German, Japanese, etc.) without altering core code.
 */
export function registerLanguage(langConfig, dictionary) {
  if (!langConfig || !langConfig.code || !dictionary) return;
  translations[langConfig.code] = dictionary;
  const existingIdx = AVAILABLE_LANGUAGES.findIndex(l => l.code === langConfig.code);
  if (existingIdx >= 0) {
    AVAILABLE_LANGUAGES[existingIdx] = langConfig;
  } else {
    AVAILABLE_LANGUAGES.push(langConfig);
  }
}

/**
 * Fetch a translation string safely via dot notation: t('nav.home') -> "Home" / "मुख्यपृष्ठ"
 * Gracefully falls back to English, then the provided fallback, then the key itself.
 */
export function getTranslation(lang, keyPath, fallback = "") {
  if (!keyPath || typeof keyPath !== 'string') return fallback || "";

  const currentLangDict = translations[lang] || translations.en;
  const parts = keyPath.split('.');

  let current = currentLangDict;
  let found = true;

  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      found = false;
      break;
    }
  }

  if (found && typeof current === 'string') {
    return current;
  }

  // Fallback to English dictionary
  let fallbackCurrent = translations.en;
  let fallbackFound = true;
  for (const fbPart of parts) {
    if (fallbackCurrent && typeof fallbackCurrent === 'object' && fbPart in fallbackCurrent) {
      fallbackCurrent = fallbackCurrent[fbPart];
    } else {
      fallbackFound = false;
      break;
    }
  }

  if (fallbackFound && typeof fallbackCurrent === 'string') {
    return fallbackCurrent;
  }

  return fallback || keyPath;
}

/**
 * Formats a date string or Date object according to the selected language locale.
 */
export function formatLocalizedDate(dateInput, lang = 'en', options = {}) {
  if (!dateInput) return '';
  try {
    const dateObj = typeof dateInput === 'string' ? new Date(dateInput) : dateInput;
    if (isNaN(dateObj.getTime())) return String(dateInput);

    const langObj = AVAILABLE_LANGUAGES.find(l => l.code === lang);
    const locale = langObj ? langObj.locale : (lang === 'hi' ? 'hi-IN' : 'en-US');

    const defaultOptions = {
      day: 'numeric',
      month: 'short',
      year: 'numeric',
      ...options
    };

    return new Intl.DateTimeFormat(locale, defaultOptions).format(dateObj);
  } catch (e) {
    return String(dateInput);
  }
}

/**
 * Formats numbers into the locale-specific numeral format if applicable.
 */
export function formatLocalizedNumber(num, lang = 'en') {
  if (num === null || num === undefined) return '';
  try {
    const langObj = AVAILABLE_LANGUAGES.find(l => l.code === lang);
    const locale = langObj ? langObj.locale : 'en-US';
    return new Intl.NumberFormat(locale).format(num);
  } catch (e) {
    return String(num);
  }
}
